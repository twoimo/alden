//! Context store behind auto-reply: a private SQLite index of chat history,
//! owner style, response timing and reply decisions, read back as reply
//! bundles.
//!
//! Each submodule owns one body of that knowledge:
//!
//! - `store` opens the context database file and guards it: private
//!   permissions, WAL, and read-only handles that fail closed.
//! - `schema` owns the tables, the retrieval-index marker and every migration.
//! - `embedding` owns the message vector and its byte encoding.
//! - `csv_import` imports an exported chat CSV into the index.
//! - `live` ingests local-DB events and owns each live source's sync state.
//! - `self_send` recognizes the assistant's own sends so they are never
//!   learned as owner style or pacing.
//! - `style` classifies owner messages and builds the owner and recipient
//!   style profiles.
//! - `topics` owns the topic lexicon and per-message topic rows.
//! - `response_time` fits the owner's reply-delay distribution.
//! - `reply_decision` records reply decisions and their status order.
//! - `search` ranks keyword, vector, topic and hybrid retrieval candidates.
//! - `reply_bundle` assembles the versioned bundle a reply worker reads.
//! - `redact` hashes provenance and strips absolute paths from output.

