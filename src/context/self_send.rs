//! Confirmed self-sends: delivery-authority evidence (`ConfirmedSelfSend`)
//! used to classify outgoing self rows and repair style samples that were
//! really the assistant's own replies.

use super::live::{
    live_event_date, refresh_live_context_summaries, LIVE_CONTEXT_BATCH_MAX_ROWS,
    LIVE_CONTEXT_MAX_FIELD_BYTES,
};
use super::reply_decision::parse_reply_sent_at_seconds;
use super::response_time::{recompute_imported_response_time_stats, MAX_RESPONSE_DELAY_SECONDS};
use super::schema::ensure_retrieval_index_current;
use super::store::{open_db, open_db_readonly, CONTEXT_DB_BUSY_TIMEOUT_SECS};
use anyhow::{Context, Result};
use rusqlite::{params, Connection, OpenFlags, OptionalExtension};
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::Path;
use std::time::Duration;

pub(super) const AUTO_GENERATED_MATCH_WINDOW_SECONDS: i64 = 120;

const AUTO_GENERATED_MATCH_MAX_CANDIDATES_PER_TEXT: usize = 16;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct OutgoingSelfEvent {
    pub chat_id: i64,
    pub log_id: i64,
    pub message: String,
    pub sent_at: i64,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct AutoGeneratedSelfEventClassification {
    pub chat_id: i64,
    pub log_id: i64,
    pub auto_generated: bool,
    pub matched_event_id: Option<String>,
    pub reason: String,
}

/// Window used to attribute an owner style row to one confirmed send.
pub const SELF_SEND_REPAIR_WINDOW_SECONDS: i64 = 180;

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct SelfSendRepairMatch {
    pub source: String,
    pub log_id: i64,
    pub date: String,
    pub message: String,
    pub content_kind: String,
    pub style_eligible_before: bool,
    pub matched_event_id: String,
    pub offset_seconds: i64,
}

#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct SelfSendRepairReport {
    pub schema_version: u32,
    pub chat: String,
    pub chat_id: i64,
    pub confirmed_sends: usize,
    pub scanned_rows: usize,
    pub matched_rows: usize,
    pub ambiguous_rows: usize,
    pub already_ineligible: usize,
    pub deleted_response_samples: usize,
    pub deleted_recipient_samples: usize,
    pub rebuilt_sources: Vec<String>,
    pub dry_run: bool,
    pub matches: Vec<SelfSendRepairMatch>,
}

/// Load the durable confirmed-send records of one chat from the decision
/// ledger. Used where no room queue is addressable (CSV import), so a bot reply
/// that was already confirmed in the context database cannot be learned as an
/// owner style sample.
pub(super) fn confirmed_self_sends_with_connection(
    conn: &Connection,
    chat: &str,
) -> Result<Vec<ConfirmedSelfSend>> {
    if chat.trim().is_empty() {
        anyhow::bail!("confirmed send chat is invalid");
    }
    let mut stmt = conn.prepare(
        "SELECT event_id, reply, sent_at, updated_at FROM reply_decisions
         WHERE chat = ?1 AND decision = 'reply' AND status = 'sent'
           AND reply IS NOT NULL AND length(trim(reply)) > 0",
    )?;
    let rows = stmt.query_map(params![chat], |row| {
        Ok((
            row.get::<_, String>(0)?,
            row.get::<_, String>(1)?,
            row.get::<_, Option<String>>(2)?,
            row.get::<_, Option<String>>(3)?,
        ))
    })?;
    let mut sends = Vec::new();
    for row in rows {
        let (event_id, text, sent_at, updated_at) = row?;
        let text = text.trim().to_string();
        if text.is_empty() {
            continue;
        }
        let Some(sent_at) = sent_at
            .as_deref()
            .and_then(owner_style_timestamp)
            .or_else(|| updated_at.as_deref().and_then(owner_style_timestamp))
        else {
            continue;
        };
        sends.push(ConfirmedSelfSend {
            event_id,
            text,
            sent_at,
        });
    }
    Ok(sends)
}

/// Match one owner style row against confirmed sends.
///
/// Returns the single matching send plus whether the match was ambiguous. A
/// many-to-one match must stay unclassified (fail closed), so callers have to
/// check the ambiguity flag before trusting the match.
pub(super) fn match_confirmed_send<'a>(
    sends: &'a [ConfirmedSelfSend],
    text: &str,
    sent_at: i64,
) -> (Option<&'a ConfirmedSelfSend>, bool) {
    let mut unique: BTreeMap<&str, &ConfirmedSelfSend> = BTreeMap::new();
    for send in sends {
        if send.text != text {
            continue;
        }
        if sent_at.abs_diff(send.sent_at) <= SELF_SEND_REPAIR_WINDOW_SECONDS as u64 {
            unique.entry(send.event_id.as_str()).or_insert(send);
        }
    }
    (unique.values().next().copied(), unique.len() > 1)
}

pub(super) fn mark_bot_sent_features(
    features_json: &str,
    event_id: &str,
    offset_seconds: i64,
) -> String {
    let mut features: serde_json::Value =
        serde_json::from_str(features_json).unwrap_or_else(|_| serde_json::json!({}));
    if let Some(object) = features.as_object_mut() {
        object.insert("style_eligible".to_string(), serde_json::json!(false));
        object.insert(
            "content_kind".to_string(),
            serde_json::json!("bot_sent_reply"),
        );
        object.insert("bot_sent_event_id".to_string(), serde_json::json!(event_id));
        object.insert(
            "bot_sent_offset_seconds".to_string(),
            serde_json::json!(offset_seconds),
        );
    }
    features.to_string()
}

fn owner_style_timestamp(value: &str) -> Option<i64> {
    chrono::NaiveDateTime::parse_from_str(value.trim(), "%Y-%m-%d %H:%M:%S")
        .ok()
        .map(|naive| naive.and_utc().timestamp())
        .or_else(|| {
            chrono::DateTime::parse_from_rfc3339(value.trim())
                .ok()
                .map(|value| value.timestamp())
        })
}

/// Mark owner style samples that the assistant itself sent as ineligible and
/// rebuild the aggregates they used to feed.
///
/// The assistant writes into the room through the owner's own account, so each
/// confirmed outgoing reply also appears in the local database as a
/// self-authored row. Ingest blocks new ones, but rows recorded before that
/// guard are already mixed into `owner_style`, its profile, the response-time
/// samples and the recipient profile. A row is repaired only for a unique,
/// exact-text confirmed send inside [`SELF_SEND_REPAIR_WINDOW_SECONDS`]; a
/// many-to-one match stays untouched (fail closed).
pub fn repair_bot_sent_style_samples(
    db_path: &Path,
    chat: &str,
    chat_id: i64,
    confirmed_sends: &[ConfirmedSelfSend],
    dry_run: bool,
) -> Result<SelfSendRepairReport> {
    if chat.trim().is_empty() || chat.len() > LIVE_CONTEXT_MAX_FIELD_BYTES {
        anyhow::bail!("style repair chat is invalid");
    }
    if chat_id <= 0 {
        anyhow::bail!("style repair chat id is invalid");
    }
    let mut conn = open_db(db_path)?;
    let rows = {
        let mut stmt = conn.prepare(
            "SELECT id, source, date, message, content_kind, style_eligible, source_row,
                    features_json
             FROM owner_style WHERE chat = ?1 ORDER BY id ASC",
        )?;
        let rows = stmt.query_map(params![chat], |row| {
            Ok((
                row.get::<_, i64>(0)?,
                row.get::<_, String>(1)?,
                row.get::<_, String>(2)?,
                row.get::<_, String>(3)?,
                row.get::<_, String>(4)?,
                row.get::<_, i64>(5)?,
                row.get::<_, i64>(6)?,
                row.get::<_, String>(7)?,
            ))
        })?;
        rows.collect::<rusqlite::Result<Vec<_>>>()?
    };

    let mut report = SelfSendRepairReport {
        schema_version: 1,
        chat: chat.to_string(),
        chat_id,
        confirmed_sends: confirmed_sends.len(),
        scanned_rows: rows.len(),
        matched_rows: 0,
        ambiguous_rows: 0,
        already_ineligible: 0,
        deleted_response_samples: 0,
        deleted_recipient_samples: 0,
        rebuilt_sources: Vec::new(),
        dry_run,
        matches: Vec::new(),
    };
    let mut affected_sources: BTreeMap<String, bool> = BTreeMap::new();
    let tx = conn.transaction()?;
    for (style_id, source, date, message, content_kind, eligible, source_row, features_json) in rows
    {
        let Some(sent_at) = owner_style_timestamp(&date) else {
            continue;
        };
        let (matched, ambiguous) = match_confirmed_send(confirmed_sends, &message, sent_at);
        if ambiguous {
            report.ambiguous_rows += 1;
            continue;
        }
        let Some(send) = matched else {
            continue;
        };
        let offset = sent_at - send.sent_at;
        report.matched_rows += 1;
        if eligible == 0 {
            report.already_ineligible += 1;
        }
        report.matches.push(SelfSendRepairMatch {
            source: source.clone(),
            log_id: source_row,
            date: date.clone(),
            message: message.clone(),
            content_kind: content_kind.clone(),
            style_eligible_before: eligible != 0,
            matched_event_id: send.event_id.clone(),
            offset_seconds: offset,
        });
        if dry_run {
            continue;
        }
        tx.execute(
            "UPDATE owner_style
             SET style_eligible = 0, content_kind = 'bot_sent_reply', features_json = ?2
             WHERE id = ?1",
            params![
                style_id,
                mark_bot_sent_features(&features_json, &send.event_id, offset)
            ],
        )?;
        let deleted_recipients = tx.execute(
            "DELETE FROM owner_recipient_style_samples WHERE style_message_id = ?1",
            params![style_id],
        )?;
        report.deleted_recipient_samples += deleted_recipients;
        let deleted_samples = if source_row > 0 {
            tx.execute(
                "DELETE FROM response_time_samples
                 WHERE source = ?1 AND chat_id = ?2 AND reply_log_id = ?3",
                params![source, chat_id, source_row],
            )?
        } else {
            0
        };
        report.deleted_response_samples += deleted_samples;
        // A source is stale whenever anything actually changed, including a row
        // that was already style-ineligible: its response-time samples were just
        // deleted, so the aggregates derived from them must be regenerated too.
        // An imported source is always re-derived: it keeps no sample rows, so a
        // bot reply that was measured before the guard existed lives only inside
        // its aggregate and nothing else can remove it.
        let is_live_source = tx
            .query_row(
                "SELECT 1 FROM context_sources WHERE source = ?1 AND chat_id = ?2",
                params![source, chat_id],
                |_| Ok(true),
            )
            .optional()?
            .unwrap_or(false);
        if !is_live_source || eligible != 0 || deleted_samples > 0 || deleted_recipients > 0 {
            affected_sources.insert(source.clone(), true);
        }
    }

    if !dry_run {
        for source in affected_sources.keys() {
            let source_chat_id = tx
                .query_row(
                    "SELECT chat_id FROM context_sources WHERE source = ?1 AND chat_id = ?2",
                    params![source, chat_id],
                    |row| row.get::<_, i64>(0),
                )
                .optional()?
                .or(tx
                    .query_row(
                        "SELECT chat_id FROM context_sources WHERE source = ?1 LIMIT 1",
                        params![source],
                        |row| row.get::<_, i64>(0),
                    )
                    .optional()?)
                .unwrap_or(0);
            if source_chat_id > 0 {
                refresh_live_context_summaries(&tx, source, source_chat_id, chat)?;
            } else {
                recompute_imported_response_time_stats(&tx, source, chat, confirmed_sends)?;
            }
            report.rebuilt_sources.push(source.clone());
        }
    }
    tx.commit()?;
    Ok(report)
}

#[derive(Debug, Clone)]
struct AutoGeneratedReplyCandidate {
    event_id: String,
    confirmed_sent: bool,
}

/// A confirmed outgoing reply taken from the room delivery authority
/// (`reply-queue.sqlite3`).
///
/// The queue stays the delivery authority, so a terminal `sent` job is direct
/// evidence that the assistant, not the owner, wrote that text into the room.
/// Style learning must not treat such a row as an owner sample: the worker's
/// own wording would otherwise be re-learned as the owner's voice (AHP:
/// style).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ConfirmedSelfSend {
    pub event_id: String,
    pub text: String,
    pub sent_at: i64,
}

/// Load the durable confirmed-send records of one room queue.
///
/// Only terminal `sent` jobs with a non-empty reply are returned. `skipped`
/// jobs never reached the composer, so they must not be able to hide a genuine
/// owner message from style learning. A missing or unreadable queue is not an
/// error: it simply contributes no evidence.
pub fn confirmed_self_sends_from_queue(queue_path: &Path) -> Result<Vec<ConfirmedSelfSend>> {
    if queue_path.is_symlink() || !queue_path.is_file() {
        return Ok(Vec::new());
    }
    let conn = Connection::open_with_flags(queue_path, OpenFlags::SQLITE_OPEN_READ_ONLY)
        .with_context(|| format!("open reply queue read-only: {}", queue_path.display()))?;
    conn.busy_timeout(Duration::from_secs(CONTEXT_DB_BUSY_TIMEOUT_SECS))?;
    let has_jobs: bool = conn
        .query_row(
            "SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'reply_jobs'",
            [],
            |_| Ok(true),
        )
        .optional()?
        .unwrap_or(false);
    if !has_jobs {
        return Ok(Vec::new());
    }
    let mut stmt = conn.prepare(
        "SELECT event_id, reply, updated_at FROM reply_jobs
         WHERE status = 'sent' AND reply IS NOT NULL AND length(trim(reply)) > 0",
    )?;
    let rows = stmt.query_map([], |row| {
        Ok((
            row.get::<_, String>(0)?,
            row.get::<_, String>(1)?,
            row.get::<_, Option<f64>>(2)?,
        ))
    })?;
    let mut sends = Vec::new();
    for row in rows {
        let (event_id, text, updated_at) = row?;
        let text = text.trim().to_string();
        let Some(sent_at) = updated_at.filter(|value| value.is_finite()) else {
            continue;
        };
        if text.is_empty() {
            continue;
        }
        sends.push(ConfirmedSelfSend {
            event_id,
            text,
            sent_at: sent_at.round() as i64,
        });
    }
    Ok(sends)
}

fn ambiguous_auto_candidate_status(status: &str) -> bool {
    matches!(
        status,
        "scheduled"
            | "sending"
            | "accepted_unconfirmed"
            | "delivery_unknown"
            | "reconcile_required"
    )
}

/// Classify a bounded page of caller-identified outgoing self rows against
/// confirmed sends. A row is marked automatic only for a unique, exact-text
/// `sent` decision within +/- 120 seconds. Exact time-bounded candidates in an
/// uncertain delivery state remain non-automatic but are explicitly excluded
/// from learning. Any many-to-one, one-to-many, or unparseable-time match is
/// likewise fail-closed and remains non-automatic.
///
/// `confirmed_sends` carries the delivery authority's own record (the room
/// queue's terminal `sent` jobs). The reply-decision ledger alone cannot prove a
/// send when the decision row was rewritten as `skip`, so both authorities are
/// unioned and the same uniqueness rule is applied across the union.
pub fn classify_auto_generated_self_events(
    db_path: &Path,
    chat: &str,
    events: &[OutgoingSelfEvent],
    confirmed_sends: &[ConfirmedSelfSend],
) -> Result<Vec<AutoGeneratedSelfEventClassification>> {
    if chat.trim().is_empty() || chat.len() > LIVE_CONTEXT_MAX_FIELD_BYTES {
        anyhow::bail!("automatic self-event classification chat is invalid");
    }
    if events.len() > LIVE_CONTEXT_BATCH_MAX_ROWS {
        anyhow::bail!("automatic self-event classification exceeds the live batch bound");
    }
    let mut identities = BTreeMap::new();
    let mut chat_id = None;
    let mut grouped: BTreeMap<&str, Vec<usize>> = BTreeMap::new();
    for (index, event) in events.iter().enumerate() {
        if event.chat_id <= 0
            || event.log_id <= 0
            || event.message.len() > LIVE_CONTEXT_MAX_FIELD_BYTES
        {
            anyhow::bail!("automatic self-event classification row is invalid");
        }
        live_event_date(event.sent_at)?;
        if chat_id
            .replace(event.chat_id)
            .is_some_and(|id| id != event.chat_id)
        {
            anyhow::bail!("automatic self-event classification spans multiple chats");
        }
        if identities
            .insert((event.chat_id, event.log_id), ())
            .is_some()
        {
            anyhow::bail!("automatic self-event classification contains a duplicate row");
        }
        grouped
            .entry(event.message.as_str())
            .or_default()
            .push(index);
    }
    if events.is_empty() {
        return Ok(Vec::new());
    }

    let conn = open_db_readonly(db_path)?;
    ensure_retrieval_index_current(&conn)?;
    let mut candidates_by_event = vec![Vec::<AutoGeneratedReplyCandidate>::new(); events.len()];
    let mut has_unparseable_candidate = vec![false; events.len()];
    let mut has_overflow_candidate = vec![false; events.len()];
    for (message, indexes) in grouped {
        if message.is_empty() {
            continue;
        }
        let minimum = indexes
            .iter()
            .map(|index| events[*index].sent_at)
            .min()
            .unwrap_or(0)
            .saturating_sub(AUTO_GENERATED_MATCH_WINDOW_SECONDS);
        let maximum = indexes
            .iter()
            .map(|index| events[*index].sent_at)
            .max()
            .unwrap_or(0)
            .saturating_add(AUTO_GENERATED_MATCH_WINDOW_SECONDS);
        let mut stmt = conn.prepare(
            "SELECT event_id, status, sent_at, created_at, updated_at,
                    scheduled_delay_seconds
             FROM reply_decisions
             WHERE chat = ?1 AND decision = 'reply' AND reply = ?2
               AND (
                    (status = 'sent'
                     AND (CAST(strftime('%s', sent_at) AS INTEGER) BETWEEN ?3 AND ?4
                          OR strftime('%s', sent_at) IS NULL))
                    OR
                    (status IN (
                        'scheduled', 'sending', 'accepted_unconfirmed',
                        'delivery_unknown', 'reconcile_required'
                     )
                     AND (
                        CAST(strftime('%s', updated_at) AS INTEGER) BETWEEN ?3 AND ?4
                        OR (CAST(strftime('%s', created_at) AS INTEGER)
                            + CAST(ROUND(scheduled_delay_seconds) AS INTEGER))
                           BETWEEN ?3 AND ?4
                        OR strftime('%s', updated_at) IS NULL
                        OR strftime('%s', created_at) IS NULL
                     ))
               )
             ORDER BY event_id ASC
             LIMIT ?5",
        )?;
        let rows = stmt.query_map(
            params![
                chat,
                message,
                minimum,
                maximum,
                (AUTO_GENERATED_MATCH_MAX_CANDIDATES_PER_TEXT + 1) as i64,
            ],
            |row| {
                Ok((
                    row.get::<_, String>(0)?,
                    row.get::<_, String>(1)?,
                    row.get::<_, Option<String>>(2)?,
                    row.get::<_, String>(3)?,
                    row.get::<_, String>(4)?,
                    row.get::<_, f64>(5)?,
                ))
            },
        )?;
        let candidates = rows.collect::<rusqlite::Result<Vec<_>>>()?;
        if candidates.len() > AUTO_GENERATED_MATCH_MAX_CANDIDATES_PER_TEXT {
            anyhow::bail!("automatic self-event match candidate set exceeds its bound");
        }
        for (event_id, status, sent_at, created_at, updated_at, scheduled_delay) in candidates {
            let confirmed_sent = status == "sent";
            if !confirmed_sent && !ambiguous_auto_candidate_status(&status) {
                anyhow::bail!("automatic self-event candidate has an unsupported status");
            }
            let candidate_times = if confirmed_sent {
                sent_at
                    .as_deref()
                    .and_then(parse_reply_sent_at_seconds)
                    .into_iter()
                    .collect::<Vec<_>>()
            } else {
                let mut times = Vec::with_capacity(2);
                if let Some(updated_at) = parse_reply_sent_at_seconds(&updated_at) {
                    times.push(updated_at);
                }
                if scheduled_delay.is_finite()
                    && (0.0..=(MAX_RESPONSE_DELAY_SECONDS as f64)).contains(&scheduled_delay)
                {
                    if let Some(scheduled_at) =
                        parse_reply_sent_at_seconds(&created_at).and_then(|created_at| {
                            created_at.checked_add(scheduled_delay.round() as i64)
                        })
                    {
                        times.push(scheduled_at);
                    }
                }
                times.sort_unstable();
                times.dedup();
                times
            };
            if candidate_times.is_empty() {
                for index in &indexes {
                    has_unparseable_candidate[*index] = true;
                }
                continue;
            }
            for index in &indexes {
                if candidate_times.iter().any(|candidate_time| {
                    events[*index].sent_at.abs_diff(*candidate_time)
                        <= AUTO_GENERATED_MATCH_WINDOW_SECONDS as u64
                }) {
                    candidates_by_event[*index].push(AutoGeneratedReplyCandidate {
                        event_id: event_id.clone(),
                        confirmed_sent,
                    });
                }
            }
        }
    }

    // Union in the delivery authority's confirmed sends. A queue `sent` job has
    // no incoming row to attach to, so it is matched by exact text inside the
    // same window and identified by its own job id.
    let mut grouped_by_text: BTreeMap<&str, Vec<usize>> = BTreeMap::new();
    for (index, event) in events.iter().enumerate() {
        if event.message.is_empty() {
            continue;
        }
        grouped_by_text
            .entry(event.message.as_str())
            .or_default()
            .push(index);
    }
    for send in confirmed_sends {
        let Some(indexes) = grouped_by_text.get(send.text.as_str()) else {
            continue;
        };
        for index in indexes {
            if events[*index].sent_at.abs_diff(send.sent_at)
                > AUTO_GENERATED_MATCH_WINDOW_SECONDS as u64
            {
                continue;
            }
            if candidates_by_event[*index]
                .iter()
                .any(|candidate| candidate.event_id == send.event_id)
            {
                continue;
            }
            if candidates_by_event[*index].len() > AUTO_GENERATED_MATCH_MAX_CANDIDATES_PER_TEXT {
                has_overflow_candidate[*index] = true;
                continue;
            }
            candidates_by_event[*index].push(AutoGeneratedReplyCandidate {
                event_id: send.event_id.clone(),
                confirmed_sent: true,
            });
        }
    }

    let mut candidate_use_counts = BTreeMap::new();
    for candidates in &candidates_by_event {
        for candidate in candidates {
            *candidate_use_counts
                .entry(candidate.event_id.as_str())
                .or_insert(0usize) += 1;
        }
    }
    Ok(events
        .iter()
        .enumerate()
        .map(|(index, event)| {
            let candidates = &candidates_by_event[index];
            let (auto_generated, matched_event_id, reason) = if has_overflow_candidate[index] {
                (false, None, "match_candidate_overflow")
            } else if has_unparseable_candidate[index] {
                (false, None, "unparseable_candidate_time")
            } else if candidates.is_empty() {
                (false, None, "no_exact_sent_match")
            } else if candidates.len() != 1 {
                (false, None, "multiple_sent_matches")
            } else if candidate_use_counts
                .get(candidates[0].event_id.as_str())
                .copied()
                .unwrap_or(0)
                != 1
            {
                (false, None, "sent_match_reused_in_batch")
            } else if !candidates[0].confirmed_sent {
                (
                    false,
                    Some(candidates[0].event_id.clone()),
                    "ambiguous_auto_candidate",
                )
            } else {
                (
                    true,
                    Some(candidates[0].event_id.clone()),
                    "unique_exact_sent_match",
                )
            };
            AutoGeneratedSelfEventClassification {
                chat_id: event.chat_id,
                log_id: event.log_id,
                auto_generated,
                matched_event_id,
                reason: reason.to_string(),
            }
        })
        .collect())
}
