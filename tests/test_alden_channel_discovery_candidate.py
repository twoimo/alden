def feed(videos, channel=CHANNEL, suffix=True):
    author = 'https://www.youtube.com/channel/' + channel
    entries = ''.join(f'''<entry><id>yt:video:{v}</id><yt:videoId>{v}</yt:videoId>
      <yt:channelId>{channel}</yt:channelId><title>같은 제목</title>
      <link rel="alternate" href="https://www.youtube.com/watch?v={v}"/>
      <author><uri>{author}</uri></author><published>2026-10-20T00:00:00Z</published>
      <updated>2026-10-20T00:00:00Z</updated></entry>''' for v in videos)
    return f'''<feed xmlns="http://www.w3.org/2005/Atom" xmlns:yt="http://www.youtube.com/xml/schemas/2015">
      <yt:channelId>{channel[2:] if suffix else channel}</yt:channelId>
      <author><uri>{author}</uri></author><link rel="alternate" href="{author}"/>{entries}</feed>'''.encode()


def native(video, *, caption=True):
    now = datetime.now(timezone.utc).isoformat()
    captions = {'availability': 'available', 'language': 'ko', 'text': '[59:55 - 01:00:03] 실제 형식 자막'} if caption else {'availability': 'access_failed', 'httpStatus': 403}
    value = {'ok': True, 'schema': 1, 'host': 'Aside', 'observedAt': now, 'captionObservedAt': now,
             'acquisition': {'provider': 'aside-native-youtube', 'host': 'local', 'account': 'u0', 'nativeReads': 3},
             'videos': [{'metadata': {'videoId': video, 'url': 'https://www.youtube.com/watch?v=' + video,
                         'title': '같은 제목', 'description': '보존된 설명'},
                         'tracks': [{'languageCode': 'ko', 'isAutoGenerated': True}], 'captions': captions}]}
    return json.dumps(value, ensure_ascii=False).encode() + b'\n\x1b[2m[ok | 7ms]\x1b[0m\n'


class ChannelDiscoveryCandidateTests(unittest.TestCase):
    def setUp(self):
        self.temporary = TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name).resolve()
        (self.root / 'candidate-channel-discovery.json').write_text(json.dumps(candidate.ROOT_MARKER))
        self.store = CollectionStore(self.root)
        self.parent = self.store.register(platform='youtube', original_id=CHANNEL, kind='channel', label='기존 채널',
                         projects=['one'], config={'adapter': 'youtube-graph', 'path': str(self.root / 'existing.json')})
        self.before = self.store.target(self.parent)
        self.expected = candidate.parent_stamp(self.before)
        self.poller = candidate.DiscoveryCandidate(self.root)
        self.feed_bytes = feed(VIDEOS[:3])
        self.feed_calls = self.native_calls = 0
        self.now = 1000

    def feed_reader(self, channel, **kwargs):
        self.assertEqual(channel, CHANNEL)
        self.assertLessEqual(kwargs['timeout'], 20)
        self.feed_calls += 1
        return self.feed_bytes

    def video_reader(self, video, **kwargs):
        self.assertLessEqual(kwargs['timeout'], 110)
        self.native_calls += 1
        return native(video)

    def step(self, **kwargs):
        return self.poller.step(self.parent, self.expected, feed_reader=self.feed_reader,
            video_reader=kwargs.pop('video_reader', self.video_reader), now=self.now, **kwargs)

    def test_additive_new_ids_same_titles_real_collection_capture_and_duplicate_replay(self):
        self.store.ingest(self.parent, [{'original_id': VIDEOS[0], 'kind': 'video', 'label': '기존', 'text': '기존 원문'}])
        before = self.store.target(self.parent)
        result = self.step()
        self.assertEqual(len(result['results']), 2)
        self.assertEqual(self.native_calls, 2)
        for row in result['results']:
            target = self.store.target(row['target'])
            collect_target(self.store, row['target'])
            capture_source(self.store, row['target'])
            self.assertEqual(target['projects'], [{'project': 'one', 'permission': 'local-private'}])
            self.assertFalse(self.poller.scheduler.acquisition_policy(row['target'])['enabled'])
        self.assertEqual(self.store.graph_page(projects=['one'])['total_nodes'], 3)
        self.assertEqual(self.store.target(self.parent), before)
        self.now += 61
        self.assertEqual(self.step()['results'], [])
        self.assertEqual(self.native_calls, 2)
        self.assertEqual(self.store.graph_page(projects=['one'])['total_nodes'], 3)

    def test_full_and_observed_suffix_ids_require_full_author_entry_and_link_identity(self):
        self.assertEqual(candidate.parse_feed(feed(VIDEOS[:1], suffix=False), CHANNEL)[0]['video_id'], VIDEOS[0])
        for raw in (feed(VIDEOS[:1]).replace(CHANNEL.encode(), ('UC'+'B'*22).encode(), 1),
                    feed(VIDEOS[:1]).replace(b'yt:video:', b'yt:other:'),
                    feed(VIDEOS[:1]).replace(b'<title>', b'<!DOCTYPE x><title>'),
                    feed([VIDEOS[0], VIDEOS[0]]), b'<feed/>', b'x'*(candidate.MAX_FEED_BYTES+1)):
            with self.subTest(prefix=raw[:60]), self.assertRaises(ValueError):
                candidate.parse_feed(raw, CHANNEL)

    def test_actual_shorts_feed_url_keeps_original_link_and_exact_canonical_video_identity(self):
        raw = feed(VIDEOS[:1]).replace(('watch?v='+VIDEOS[0]).encode(), ('shorts/'+VIDEOS[0]).encode())
        item = candidate.parse_feed(raw, CHANNEL)[0]
        self.assertEqual(item['url'], 'https://www.youtube.com/shorts/' + VIDEOS[0])
        self.assertEqual(item['canonical_url'], 'https://www.youtube.com/watch?v=' + VIDEOS[0])
        for altered in (raw.replace(('shorts/'+VIDEOS[0]).encode(), ('shorts/'+VIDEOS[1]).encode()),
                        raw.replace(('shorts/'+VIDEOS[0]).encode(), ('shorts/'+VIDEOS[0]+'?other=1').encode())):
            with self.assertRaisesRegex(ValueError, 'video_channel_mismatch'):
                candidate.parse_feed(altered, CHANNEL)

    def test_after_acquisition_process_restart_uses_original_cli_bytes_with_trailer(self):
        def crash(stage):
            if stage == 'acquired': raise KeyboardInterrupt()
        with self.assertRaises(KeyboardInterrupt): self.step(max_videos=1, after_stage=crash)
        self.assertEqual(self.native_calls, 1)
        self.poller = candidate.DiscoveryCandidate(self.root)
        result = self.step(max_videos=1)
        self.assertEqual(result['results'][0]['state'], 'registered')
        self.assertEqual(self.native_calls, 1)

    def test_after_canonical_commit_process_restart_reconciles_without_duplicate(self):
        def crash(stage):
            if stage == 'published': raise KeyboardInterrupt()
        with self.assertRaises(KeyboardInterrupt): self.step(max_videos=1, after_stage=crash)
        target = identity('target-youtube', 'video:' + VIDEOS[0])
        before = self.store.target(target)
        self.poller = candidate.DiscoveryCandidate(self.root)
        self.assertEqual(self.step(max_videos=1)['results'][0]['state'], 'registered')
        self.assertEqual(self.store.target(target), before)
        self.assertEqual(self.native_calls, 1)

    def test_existing_target_definition_and_permissions_are_never_overwritten(self):
        old = self.store.register(platform='youtube', original_id=VIDEOS[0], kind='video', label='다른 기존 대상',
                     projects=['other'], permission='denied', config={'adapter': 'youtube-video', 'path': 'unchanged'})
        before = self.store.target(old)
        self.step()
        self.assertEqual(self.native_calls, 2)
        self.assertEqual(self.store.target(old), before)

    def test_parent_permission_revoked_during_read_prevents_registration(self):
        def reader(video, **kwargs):
            raw = self.video_reader(video, **kwargs)
            with self.store.database() as db:
                db.execute("UPDATE target_projects SET permission='denied' WHERE target_id=?", (self.parent,))
            return raw
        with self.assertRaisesRegex(ValueError, 'parent_changed'):
            self.step(video_reader=reader)
        with self.store.database() as db:
            self.assertEqual(db.execute('SELECT count(*) FROM targets').fetchone()[0], 1)

    def test_pause_during_native_read_keeps_staged_receipt_without_publishing(self):
        def reader(video, **kwargs):
            raw = self.video_reader(video, **kwargs)
            self.poller.scheduler.pause(True, self.parent)
            return raw
        with self.assertRaises(AldenCancelled): self.step(video_reader=reader)
        with self.store.database() as db:
            self.assertEqual(db.execute('SELECT count(*) FROM targets').fetchone()[0], 1)
        self.poller.scheduler.pause(False, self.parent)
        self.step(max_videos=1)
        self.assertEqual(self.native_calls, 1)

    def test_stop_inside_publication_rolls_back_canonical_target_and_no_corpus_event(self):
        stop = [False]
        save = candidate._save_once
        def during_write(path, raw):
            save(path, raw)
            if path.name == 'current.json': stop[0] = True
        with patch.object(candidate, '_save_once', side_effect=during_write), self.assertRaises(AldenCancelled):
            self.step(max_videos=1, stopped=lambda: stop[0])
        with self.store.database() as db:
            self.assertEqual(db.execute('SELECT count(*) FROM targets').fetchone()[0], 1)
            self.assertEqual(db.execute('SELECT count(*) FROM documents').fetchone()[0], 0)

    def test_empty_and_malformed_feed_do_not_prune_frontier_and_poll_has_floor(self):
        self.step(max_videos=1)
        self.feed_bytes = b'<feed/>'
        self.step(max_videos=1)
        self.assertEqual(self.feed_calls, 1)
        self.now += 61
        self.assertEqual(self.step()['state'], 'feed_failed')
        with self.poller.db() as db:
            self.assertEqual(db.execute('SELECT count(*) FROM frontier').fetchone()[0], 3)
        self.feed_bytes = feed([])
        self.now += 61
        self.step()
        with self.poller.db() as db:
            self.assertEqual(db.execute("SELECT count(*) FROM frontier WHERE state='registered'").fetchone()[0], 3)

    def test_rate_limit_holds_all_channels_without_retry_or_identity_switch(self):
        def limited(video, **kwargs):
            self.native_calls += 1
            return b'{"ok":false,"stage":"captions","httpStatus":429}'
        self.assertEqual(self.step(video_reader=limited)['state'], 'partial')
        self.now += 99999
        self.assertEqual(self.step()['state'], 'blocked')
        self.assertEqual(self.native_calls, 1)
        parent2 = self.store.register(platform='youtube', original_id='UC'+'B'*22, kind='channel', label='다른 채널',
                   projects=['one'], config={'adapter':'youtube-graph'})
        result = self.poller.step(parent2, candidate.parent_stamp(self.store.target(parent2)),
                    feed_reader=lambda *a, **k: self.fail('provider hold must cover new channels'), video_reader=self.video_reader)
        self.assertEqual(result['state'], 'blocked')

    def test_transient_failure_backoff_retries_a_new_receipt_without_old_hash_conflict(self):
        self.step(max_videos=1, video_reader=lambda *a, **k: b'{"ok":false,"stage":"metadata","httpStatus":503}')
        self.now += 121
        result = self.step(max_videos=1)
        self.assertEqual(result['results'][0]['state'], 'registered')
        with self.poller.db() as db:
            row = db.execute('SELECT attempts,state FROM frontier ORDER BY rowid LIMIT 1').fetchone()
            self.assertEqual(tuple(row), (2, 'registered'))

    def test_failed_caption_is_explicit_description_only_without_false_transcript(self):
        result = self.step(max_videos=1, video_reader=lambda video, **k: native(video, caption=False))
        target = result['results'][0]['target']
        collect_target(self.store, target)
        node = self.store.graph_page(projects=['one'])['nodes'][0]
        detail = self.store.graph_page(projects=['one'], focus=node['id'], hops=0, details=True, expected_version=node['source_version'])['details']
        self.assertEqual(detail['body'], '보존된 설명')

    def test_candidate_rejects_unmarked_or_live_stores(self):
        with self.assertRaisesRegex(ValueError, 'live_root_forbidden'):
            candidate.DiscoveryCandidate(Path.home()/'Library/Application Support/openkakao/bujamentor')
        (self.root / 'candidate-channel-discovery.json').unlink()
        with self.assertRaises(FileNotFoundError): candidate.DiscoveryCandidate(self.root)

    def test_recovery_never_reenables_or_regrants_an_edited_child(self):
        def crash(stage):
            if stage == 'published': raise KeyboardInterrupt()
        with self.assertRaises(KeyboardInterrupt): self.step(max_videos=1, after_stage=crash)
        child = identity('target-youtube', 'video:' + VIDEOS[0])
        with self.store.database() as db:
            db.execute('UPDATE targets SET enabled=0 WHERE id=?', (child,))
        before = self.store.target(child)
        self.assertEqual(self.step(max_videos=1)['results'][0]['reason'], 'discovery_existing_target_conflict')
        self.assertEqual(self.store.target(child), before)
        self.assertEqual(self.native_calls, 1)

    def test_retained_native_hash_mutation_blocks_recovery(self):
        def crash(stage):
            if stage == 'acquired': raise KeyboardInterrupt()
        with self.assertRaises(KeyboardInterrupt): self.step(max_videos=1, after_stage=crash)
        path = next((self.poller.folder / 'native').rglob('*.json'))
        path.write_bytes(native(VIDEOS[0]) + b' ')
        self.assertEqual(self.step(max_videos=1)['results'][0]['reason'], 'discovery_native_recovery_hash_changed')
        self.assertEqual(self.native_calls, 1)
        with self.store.database() as db:
            self.assertEqual(db.execute('SELECT count(*) FROM targets').fetchone()[0], 1)

    def test_repeated_denial_stops_provider_without_consuming_remaining_jobs(self):
        def denied(video, **kwargs):
            self.native_calls += 1
            return b'{"ok":false,"stage":"metadata","httpStatus":403}'
        self.step(video_reader=denied)
        self.assertEqual(self.native_calls, 2)
        self.assertEqual(self.step()['reason'], 'discovery_repeated_native_403')

    def test_emergency_voice_and_existing_pause_prevent_host_reads(self):
        self.poller.scheduler.pause(True)
        with self.assertRaises(AldenCancelled): self.step()
        self.poller.scheduler.pause(False)
        with patch.object(self.poller.scheduler, '_voice_busy', return_value=True), self.assertRaises(AldenCancelled):
            self.step()
        AbortController(self.root / ABORT_STATE_NAME).abort('isolated test')
        with self.assertRaises(AldenCancelled): self.step()
        self.assertEqual((self.feed_calls, self.native_calls), (0, 0))

    def test_retained_feed_mutation_blocks_context_publication(self):
        def crash(stage):
            if stage == 'acquired': raise KeyboardInterrupt()
        with self.assertRaises(KeyboardInterrupt): self.step(max_videos=1, after_stage=crash)
        path = next((self.poller.folder / 'feeds').glob('*.xml'))
        path.write_bytes(path.read_bytes() + b' ')
        self.assertEqual(self.step(max_videos=1)['results'][0]['reason'], 'discovery_feed_recovery_hash_changed')
        self.assertEqual(self.native_calls, 1)

    def test_partial_native_envelope_cannot_hide_a_provider_rate_limit(self):
        def limited(video, **kwargs):
            value = candidate._decode(native(video, caption=False))
            value['videos'][0]['captions']['httpStatus'] = 429
            return json.dumps(value).encode()
        self.step(max_videos=1, video_reader=limited)
        self.assertEqual(self.step()['reason'], 'discovery_native_http_429')
        with self.store.database() as db:
            self.assertEqual(db.execute('SELECT count(*) FROM targets').fetchone()[0], 1)

    def test_busy_canonical_transaction_reuses_retained_input_after_rollback(self):
        save = candidate._save_once
        def busy(path, raw):
            save(path, raw)
            if path.name == 'current.json': raise sqlite3.OperationalError('database is locked')
        with patch.object(candidate, '_save_once', side_effect=busy):
            self.assertEqual(self.step(max_videos=1)['results'][0]['state'], 'failed')
        with self.store.database() as db:
            self.assertEqual(db.execute('SELECT count(*) FROM targets').fetchone()[0], 1)
        self.now += 121
        self.assertEqual(self.step(max_videos=1)['results'][0]['state'], 'registered')
        self.assertEqual(self.native_calls, 1)


